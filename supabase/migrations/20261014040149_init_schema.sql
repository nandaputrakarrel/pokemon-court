create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public."user data" (id) values (new.id);
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.set_feedback_email()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.email is null then
    select email into new.email from auth.users where id = new.user_id;
  end if;
  return new;
end;
$$;

create trigger feedback_capture_email
before insert on public.feedback
for each row execute function public.set_feedback_email();

create or replace function public.clear_feedback_email_on_account_delete()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.feedback
  set email = null
  where user_id = old.id;
  return old;
end;
$$;

create trigger feedback_clear_email_on_user_delete
after delete on auth.users
for each row execute function public.clear_feedback_email_on_account_delete();

