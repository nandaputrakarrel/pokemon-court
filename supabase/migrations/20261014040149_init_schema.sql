create or replace function public.get_user_tournament_and_battle_logs_v5(user_id uuid)
returns table (
  source text,
  deck text,
  decklist_id uuid,
  opp_deck text,
  result text,
  match_end_reason text,
  turn_order text,
  date timestamptz,
  format text
)
language sql
stable
security invoker
set search_path = public
as $$
  select
    'Battle Logs'::text,
    logs.archetype,
    logs.decklist_id,
    logs.opp_archetype,
    logs.result,
    null::text,
    logs.turn_order,
    logs.created_at,
    logs.format
  from public.logs
  where logs."user" = user_id
    and logs.archetype is not null
    and logs.opp_archetype is not null
    and logs.result is not null

  union all

  select
    'Tournament Rounds'::text,
    tournaments.deck,
    tournaments.decklist_id,
    rounds.deck,
    game.result,
    rounds.match_end_reason,
    game.turn_order,
    coalesce(tournaments.date_from, rounds.created_at),
    tournaments.format
  from public."tournament rounds" as rounds
  join public.tournaments on tournaments.id = rounds.tournament
  cross join lateral (
    select
      rounds.result[idx] as result,
      case
        when rounds.turn_orders is not null and idx <= cardinality(rounds.turn_orders)
          then rounds.turn_orders[idx]
        else null
      end as turn_order
    from generate_subscripts(rounds.result, 1) as idx
  ) as game
  where rounds."user" = user_id
    and tournaments.deck is not null
    and rounds.deck is not null
    and coalesce(rounds.match_end_reason, '') not in ('ID', 'No show', 'Bye');
$$;

