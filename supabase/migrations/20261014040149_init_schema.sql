create or replace function public.getusertournamentresults(userid uuid)
returns table (
  tournament_deck text,
  round_deck text,
  total_wins bigint,
  total_losses bigint,
  total_ties bigint,
  total_matches bigint,
  win_rate double precision,
  tie_rate double precision
)
language sql
stable
security invoker
set search_path = public
as $$
  with games as (
    select
      tournaments.deck as tournament_deck,
      rounds.deck as round_deck,
      game.result
    from public."tournament rounds" as rounds
    join public.tournaments on tournaments.id = rounds.tournament
    cross join lateral unnest(rounds.result) as game(result)
    where rounds."user" = userid
      and tournaments.deck is not null
      and rounds.deck is not null
      and coalesce(rounds.match_end_reason, '') not in ('ID', 'No show', 'Bye')
  )
  select
    games.tournament_deck,
    games.round_deck,
    count(*) filter (where games.result = 'W')::bigint,
    count(*) filter (where games.result = 'L')::bigint,
    count(*) filter (where games.result is distinct from 'W' and games.result is distinct from 'L')::bigint,
    count(*)::bigint,
    case
      when count(*) = 0 then 0
      else count(*) filter (where games.result = 'W')::double precision / count(*)::double precision
    end,
    case
      when count(*) = 0 then 0
      else count(*) filter (where games.result is distinct from 'W' and games.result is distinct from 'L')::double precision / count(*)::double precision
    end
  from games
  group by games.tournament_deck, games.round_deck;
$$;

