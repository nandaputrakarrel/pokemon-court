create or replace function public.get_authenticated_user_matchup_aggregates_v1()
returns table (
  source text,
  deck text,
  decklist_id uuid,
  opp_deck text,
  format text,
  wins bigint,
  losses bigint,
  ties bigint,
  going_first_wins bigint,
  going_first_losses bigint,
  going_first_ties bigint,
  going_second_wins bigint,
  going_second_losses bigint,
  going_second_ties bigint,
  last_played timestamptz
)
language sql
stable
security invoker
set search_path = public
as $$
  select
    matches.source,
    matches.deck,
    matches.decklist_id,
    matches.opp_deck,
    matches.format,
    count(*) filter (where matches.result = 'W')::bigint,
    count(*) filter (where matches.result = 'L')::bigint,
    count(*) filter (where matches.result is distinct from 'W' and matches.result is distinct from 'L')::bigint,
    count(*) filter (where matches.turn_order = '1' and matches.result = 'W')::bigint,
    count(*) filter (where matches.turn_order = '1' and matches.result = 'L')::bigint,
    count(*) filter (where matches.turn_order = '1' and matches.result is distinct from 'W' and matches.result is distinct from 'L')::bigint,
    count(*) filter (where matches.turn_order = '2' and matches.result = 'W')::bigint,
    count(*) filter (where matches.turn_order = '2' and matches.result = 'L')::bigint,
    count(*) filter (where matches.turn_order = '2' and matches.result is distinct from 'W' and matches.result is distinct from 'L')::bigint,
    max(matches.date)
  from public.get_user_tournament_and_battle_logs_v5(auth.uid()) as matches
  group by matches.source, matches.deck, matches.decklist_id, matches.opp_deck, matches.format;
$$;

