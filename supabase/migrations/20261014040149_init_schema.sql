create table public."user data" (
  -- No FK to auth.users so account deletion can remove auth access
  -- while leaving logs and tournaments attached to this profile row.
  id uuid primary key,
  created_at timestamptz not null default timezone('utc', now()),
  avatar text,
  live_screen_name text,
  preferred_games text[] default '{}'::text[]
);

create table public.decklists (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  user_id uuid not null references public."user data" (id) on delete cascade,
  name text not null,
  game text not null default 'pokemon-tcg',
  cards jsonb not null,
  content_hash text,
  archetype text,
  format text
);

create table public.logs (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default timezone('utc', now()),
  "user" uuid not null references public."user data" (id) on delete restrict,
  log text not null,
  notes text,
  archetype text,
  opp_archetype text,
  result text,
  turn_order text,
  format text not null default '',
  decklist_id uuid references public.decklists (id) on delete set null
