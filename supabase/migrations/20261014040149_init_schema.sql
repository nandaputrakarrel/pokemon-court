create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select auth.uid() in (
    '01a36333-aa26-47e1-bec6-bbdd596a7020'::uuid,
    '830cc5da-0dc2-44cf-a2b4-676090922637'::uuid,
    'f0a37b75-3ecb-4aaa-a5ac-ecb679685ed2'::uuid
  );
$$;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

